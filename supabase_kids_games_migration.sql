-- =============================================================================
-- LIVING ENGLISH — TABLA Y SEMILLA DE DATOS PARA JUEGOS DE NIÑOS (kids_games)
-- Ejecuta este script en el SQL Editor de Supabase para crear la tabla
-- `public.kids_games` con 180 palabras ilustradas con emojis en 12 categorías.
-- =============================================================================

CREATE TABLE IF NOT EXISTS public.kids_games (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  word TEXT NOT NULL,
  emoji TEXT NOT NULL,
  category TEXT NOT NULL,
  spanish_hint TEXT,
  active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Índices para consultas rápidas por categoría y estado activo
CREATE INDEX IF NOT EXISTS idx_kids_games_category ON public.kids_games (category);
CREATE INDEX IF NOT EXISTS idx_kids_games_active ON public.kids_games (active);

-- Habilitar Row Level Security (RLS) con lectura pública para la plataforma
ALTER TABLE public.kids_games ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir lectura publica de kids_games" ON public.kids_games;
CREATE POLICY "Permitir lectura publica de kids_games"
  ON public.kids_games
  FOR SELECT
  USING (true);

-- Limpiar registros previos si se vuelve a ejecutar la semilla
TRUNCATE TABLE public.kids_games RESTART IDENTITY;

